"""Table definitions.

Four tables, and only four, because nothing else exists yet. `chunks` is the
RAG corpus, `messages` is the draft-then-approve inbox, and the two log tables
record what happened. They are plain SQLAlchemy models rather than an ORM used
by the services, because Alembic autogenerates the migration from them and
nothing else needs them.

The vector column is `vector(384)`, matching the local embedding model's output.
A query embedding from a different model has no meaningful distance to these,
which is why the model name is a setting and the dimension is asserted in tests.
"""

from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    Boolean,
    Computed,
    DateTime,
    Enum,
    Float,
    Identity,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy import text as sql_text
from sqlalchemy.dialects.postgresql import DATE, TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Every state a visitor message can be in.
#
# `sending` is the intermediate state the atomic claim moves a row into, before
# the provider call. Without it, a crash during the send would leave a row as
# `pending` forever with no way to tell whether the mail went out — which is the
# one question that matters if a visitor disputes it. `reap_stale_sends` resolves
# those to `failed`.
#
# Mirrored in the migration's `MESSAGE_STATUSES`; the two must agree or
# `alembic check` proposes a type change.
MESSAGE_STATUSES = ("pending", "sending", "sent", "expired", "failed", "cancelled")


class Base(DeclarativeBase):
    pass


# Nearest-neighbour index over the embeddings is declared on `Chunk` itself, in
# its `__table_args__`. It has to live in the metadata, not only in the
# migration's raw SQL: an index that exists in the database but not in the
# models makes `alembic check` and every future autogenerate propose dropping
# it, which is how a hand-written index quietly disappears.
#
# `lakebase_ann` is Neon's index access method, installed with the
# lakebase_vector extension. `vector_cosine_ops` pairs with the `<=>` distance
# operator used in the retrieval query; an operator class and an operator that
# disagree is the quiet-wrong-answer bug, because the query still runs and just
# returns worse matches.


class Chunk(Base):
    """One slice of a corpus document, with its embedding.

    The unique constraint on (source_path, chunk_index) is what makes re-running
    the ingest idempotent. Without it, every ingest of an edited document adds
    a second copy of the same text and retrieval starts returning duplicates.
    """

    __tablename__ = "chunks"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    source_path: Mapped[str] = mapped_column(String(512), nullable=False)
    chunk_index: Mapped[int] = mapped_column(Integer, nullable=False)
    heading: Mapped[str] = mapped_column(String(512), default="")
    content: Mapped[str] = mapped_column(Text, nullable=False)
    embedding: Mapped[list[float]] = mapped_column(Vector(384), nullable=False)
    # Generated by the database from `content`, so it cannot drift from what it
    # indexes. Used for the lexical half of hybrid retrieval.
    #
    # GENERATED ALWAYS is not expressible in SQLAlchemy's `mapped_column`, so
    # this is declared `Computed` on the model and the same expression appears in
    # the migration. Both must agree or `alembic check` proposes dropping a
    # column it can see but cannot produce, which is how a generated column
    # disappears by accident.
    body_tsv: Mapped[str | None] = mapped_column(
        TSVECTOR,
        Computed("to_tsvector('english', content)", persisted=True),
        nullable=True,
    )
    # Stored so a chunk can be budgeted into a prompt without re-tokenising it.
    token_count: Mapped[int] = mapped_column(Integer, default=0)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
        UniqueConstraint("source_path", "chunk_index", name="uq_chunks_source_index"),
        # `lists = 'auto'` would let the index size its own IVF partition layout;
        # the default suits a corpus this small, where the planner prefers an
        # exact scan anyway. This index is insurance for growth, not a speedup
        # on day one.
        Index(
            "ix_chunks_embedding_ann",
            "embedding",
            postgresql_using="lakebase_ann",
            postgresql_with={"build_mode": "standard"},
        ),
        # The lexical half of hybrid retrieval. GIN over the generated tsvector.
        Index("ix_chunks_body_tsv", "body_tsv", postgresql_using="gin"),
    )


class Message(Base):
    """A visitor's message, written before it is sent.

    Phase 5 only ever writes `pending`. The send route in phase 6 moves it to
    `sent`, and nothing can send anything without an explicit approval.

    `approval_token_hash` is a SHA-256 of the token handed to the browser, so a
    leaked database row cannot be replayed into sending mail. `expires_at` bounds
    that capability in time.
    """

    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    email: Mapped[str] = mapped_column(String(320), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    # server_default as well as the Python default. The column is NOT NULL, so
    # any writer that is not the ORM — a psql session, a future admin script,
    # a migration — would hit a constraint violation without it.
    #
    # An enum, not free text. A typo in the phase-6 update would otherwise write
    # 'confimed' and the approval route would treat the message as pending
    # forever. The database should refuse it.
    #
    # create_type=False: the migration owns the type, and creating it a second
    # time here would make `alembic check` propose a change on every run.
    status: Mapped[str] = mapped_column(
        Enum(
            *MESSAGE_STATUSES,
            name="message_status",
            create_type=False,
            validate_strings=True,
        ),
        default="pending",
        server_default="pending",
        nullable=False,
    )
    approval_token_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    # The POST /messages/drafts form's context fields. Nullable: chat-created
    # drafts (`draft_message`) take none of them, and an absent value arriving
    # in the email as a blank line is worse than it not arriving.
    company: Mapped[str | None] = mapped_column(String(200), nullable=True)
    role: Mapped[str | None] = mapped_column(String(200), nullable=True)
    subject: Mapped[str | None] = mapped_column(String(200), nullable=True)
    # A salted SHA-256 of the visitor's normalised address, never the address
    # itself. Nulled the moment the message is sent: the IP's only job is to bind
    # a draft to the connection that wrote it, and that job ends at approval.
    #
    # `origin_ip` is kept alongside it rather than dropped, so the change is
    # backwards compatible — see ADR 0006 on migrate-first ordering.
    origin_ip: Mapped[str | None] = mapped_column(String(45), nullable=True)
    ip_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # When the send capability stops working. A NULL here would read as "never
    # expires" to every query that checks it, which is the opposite of the point.
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    # Set when Resend returns an id, in phase 6. Nullable because nothing sets it
    # yet.
    sent_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    provider_id: Mapped[str | None] = mapped_column(String(255))

    __table_args__ = (
        # Phase 6 reads the inbox by status. Without this it is a sequential scan
        # of every message ever drafted.
        Index("ix_messages_status", "status"),
        # Partial: pending drafts are a tiny fraction of the table and are the
        # only rows any query filters for.
        Index(
            "ix_messages_pending",
            "created_at",
            postgresql_where=sql_text("status = 'pending'"),
        ),
        # A row with a hash still holds a traceable identifier; these are the rows
        # the sweep's work is on. Partial, so it stays empty on a quiet site.
        Index(
            "ix_messages_retained",
            "expires_at",
            postgresql_where=sql_text("ip_hash IS NOT NULL"),
        ),
    )


class SendCounter(Base):
    """One row per day. The table *is* the daily send cap.

    In the database rather than in process because an in-process counter resets
    on every Render spin-down: ten sends before a sleep and ten after would be
    twenty. `day` is the primary key, which is what lets
    `INSERT ... ON CONFLICT (day) DO UPDATE ... WHERE count < :cap` be the cap
    check itself — one atomic statement, no read-modify-write.
    """

    __tablename__ = "send_counters"

    day: Mapped[datetime.date] = mapped_column(DATE, primary_key=True)
    count: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")


class IpSendCounter(Base):
    """The same day-counter trick, per actor: (day, ip_hash) is the cap.

    The actor is the salted digest from ADR 0006, not the address; ADR 0011
    records the tradeoff of keeping that digest for one day. Same atomic
    single-statement cap as `SendCounter`, primary key `(day, ip_hash)`.

    Retention deletes anything past its day — this is an anti-abuse counter,
    never a log.
    """

    __tablename__ = "ip_send_counters"

    day: Mapped[datetime.date] = mapped_column(DATE, primary_key=True)
    ip_hash: Mapped[str] = mapped_column(String(64), primary_key=True)
    count: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")


class IngestRun(Base):
    """One pass of the corpus importer.

    Records which embedding model produced the rows. Rows written by two
    different models are not comparable, so this is the thing you check first
    when retrieval quality changes without the corpus changing.
    """

    __tablename__ = "ingest_runs"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    chunk_count: Mapped[int] = mapped_column(Integer, default=0)
    embedding_model: Mapped[str] = mapped_column(String(255), nullable=False)
    embedding_dimensions: Mapped[int] = mapped_column(Integer, nullable=False)


class ToolCallLog(Base):
    """One row per tool invocation.

    `latency_ms` is here because the interesting production failure is rarely
    an exception; it is a tool that quietly got ten times slower.
    """

    __tablename__ = "tool_call_log"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    name: Mapped[str] = mapped_column(String(100), nullable=False)
    ok: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    latency_ms: Mapped[float] = mapped_column(Float, default=0.0)
    # Arguments with secrets stripped: the raw dict can contain an API key.
    arguments: Mapped[str] = mapped_column(Text, default="{}")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
        # The evals and any abuse investigation both read this newest-first.
        Index("ix_tool_call_log_created_at", "created_at"),
    )
